#!/usr/bin/env node
// Turns the private advent content (advent/private/content.js) into a SQL file
// you paste into the Supabase SQL editor. It picks which question, challenge
// and memory prompt lands on each day, using the same schedule as the page.
//
//   node scripts/advent-content.js
//
// Writes (both gitignored):
//   advent/private/content.sql         paste this into Supabase
//   advent/private/preview-seed.json   used to build the try-out preview
//
// Re-running is safe: days that have already opened keep their content, so
// opened days never change. Only unopened days get (re)assigned.

const fs = require("fs");
const path = require("path");
const vm = require("vm");

const root = path.join(__dirname, "..", "advent");
const { shuffle, rng, buildSchedule } = require(path.join(root, "schedule.js"));
const content = require(path.join(root, "private", "content.js"));

// config.js is written for the browser (window.ADVENT_CONFIG = …).
const sandbox = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(root, "config.js"), "utf8"), sandbox);
const CFG = sandbox.window.ADVENT_CONFIG;

const hashStr = (s) => [...s].reduce((h, c) => (Math.imul(h, 31) + c.charCodeAt(0)) | 0, 7);
const schedule = buildSchedule(CFG);

// Check ids are unique.
const seen = new Set();
for (const [type, items] of Object.entries(content)) {
  for (const it of items) {
    if (seen.has(it.id)) throw new Error(`Duplicate id "${it.id}" in ${type}`);
    seen.add(it.id);
  }
}

const rows = {};
for (const type of ["question", "challenge", "memory"]) {
  const days = schedule.filter((s) => s.type === type).map((s) => s.day);
  const pool = content[type] || [];
  if (pool.length < days.length) {
    throw new Error(`Need at least ${days.length} ${type} items, only have ${pool.length}`);
  }
  const picked = shuffle(pool, rng(CFG.SEED + hashStr(type)));
  days.forEach((d, i) => {
    rows[`day:${d}:content`] = { type, id: picked[i].id, text: picked[i].text };
  });
}
rows["pool:spinner"] = content.spinner.map(({ id, text }) => ({ id, text }));
rows["pool:coupon"] = content.coupon.map(({ id, text }) => ({ id, text }));
// For the notification sender: names, and each day's type ("Door 5: question day").
rows["pool:people"] = CFG.PEOPLE.map(({ id, name }) => ({ id, name }));
rows["pool:schedule"] = schedule.map((s) => s.type);

const q = (s) => "'" + String(s).replace(/'/g, "''") + "'";
const values = Object.entries(rows)
  .map(([k, v]) => `  (${q(k)}, ${q(JSON.stringify(v))}::jsonb)`)
  .join(",\n");

const sql = `-- PRIVATE advent content. Generated by scripts/advent-content.js — don't
-- commit this file. Paste the whole thing into Supabase: SQL Editor -> New query -> Run.
-- Days that have already opened keep what they had.

insert into public.advent_kv (key, value)
values
${values}
on conflict (key) do update
  set value = excluded.value, updated_at = clock_timestamp()
  where not (
    advent_kv.key ~ '^day:[0-9]+:content$'
    and split_part(advent_kv.key, ':', 2)::int <= public.advent_day()
  );
`;

fs.writeFileSync(path.join(root, "private", "content.sql"), sql);
fs.writeFileSync(path.join(root, "private", "preview-seed.json"), JSON.stringify(rows, null, 2));

console.log("Wrote advent/private/content.sql and preview-seed.json");
console.log(`${Object.keys(rows).length} rows written`);
